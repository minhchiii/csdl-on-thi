// Copy vendor assets: KaTeX, fonts (subsets latin, latin-ext, vietnamese), Lucide icons -> assets/js/icons.js
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..');
const NM = path.join(__dirname, 'npm', 'node_modules');
const V = path.join(ROOT, 'vendor');
function cp(src, dst) { fs.mkdirSync(path.dirname(dst), { recursive: true }); fs.copyFileSync(src, dst); }
function cpDir(src, dst, filter = () => true) {
  fs.mkdirSync(dst, { recursive: true });
  for (const f of fs.readdirSync(src)) {
    const s = path.join(src, f), d = path.join(dst, f);
    if (fs.statSync(s).isDirectory()) cpDir(s, d, filter); else if (filter(f)) cp(s, d);
  }
}
// KaTeX
const K = path.join(NM, 'katex', 'dist');
cp(path.join(K, 'katex.min.js'), path.join(V, 'katex', 'katex.min.js'));
cp(path.join(K, 'katex.min.css'), path.join(V, 'katex', 'katex.min.css'));
cp(path.join(K, 'contrib', 'auto-render.min.js'), path.join(V, 'katex', 'auto-render.min.js'));
cpDir(path.join(K, 'fonts'), path.join(V, 'katex', 'fonts'), f => f.endsWith('.woff2'));
// Fonts
const fonts = [
  ['lora', 'Lora', [400, 500, 600, 700], true],
  ['inter', 'Inter', [400, 500, 600, 700], false],
  ['jetbrains-mono', 'JetBrains Mono', [400, 500, 700], false],
];
const subsets = { 'vietnamese': 'U+0102-0103,U+0110-0111,U+0128-0129,U+0168-0169,U+01A0-01A1,U+01AF-01B0,U+0300-0301,U+0303-0304,U+0308-0309,U+0323,U+0329,U+1EA0-1EF9,U+20AB',
  'latin-ext': 'U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF',
  'latin': 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD' };
let css = '/* generated by tools/vendor.js */\n';
for (const [pkg, fam, weights, italic] of fonts) {
  for (const w of weights) for (const style of italic ? ['normal', 'italic'] : ['normal']) {
    if (style === 'italic' && w !== 400) continue;
    for (const [sub, range] of Object.entries(subsets)) {
      const fn = `${pkg}-${sub}-${w}-${style}.woff2`;
      const src = path.join(NM, '@fontsource', pkg, 'files', fn);
      if (!fs.existsSync(src)) { console.warn('missing', fn); continue; }
      cp(src, path.join(V, 'fonts', fn));
      css += `@font-face{font-family:'${fam}';font-style:${style};font-weight:${w};font-display:swap;src:url(${fn}) format('woff2');unicode-range:${range};}\n`;
    }
  }
}
fs.writeFileSync(path.join(V, 'fonts', 'fonts.css'), css);
// Icons
const icons = ['book-open', 'layers', 'list-checks', 'pen-line', 'sun', 'moon', 'table-2', 'x', 'check', 'rotate-ccw',
  'timer', 'upload', 'download', 'filter', 'chevron-left', 'chevron-right', 'chevron-down', 'eye', 'eye-off', 'flag',
  'circle-help', 'info', 'shuffle', 'play', 'square', 'trash-2', 'search', 'lightbulb', 'bookmark', 'menu', 'file-json',
  'circle-check', 'circle-x', 'triangle-alert', 'repeat', 'copy', 'sigma', 'graduation-cap', 'arrow-right', 'list'];
const out = {};
for (const n of icons) {
  const f = path.join(NM, 'lucide-static', 'icons', n + '.svg');
  if (!fs.existsSync(f)) { console.warn('missing icon', n); continue; }
  let s = fs.readFileSync(f, 'utf8').replace(/<!--[\s\S]*?-->/g, '').replace(/\s*\n\s*/g, ' ').trim();
  const inner = s.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '').trim();
  out[n] = inner;
}
fs.writeFileSync(path.join(ROOT, 'assets', 'js', 'icons.js'),
  '// Lucide icons (ISC License) – generated by tools/vendor.js\nwindow.ICONS = ' + JSON.stringify(out, null, 0) + ';\n' +
  "window.icon = function (name, size) { size = size || 16; return '<svg class=\"ic\" width=\"' + size + '\" height=\"' + size + '\" viewBox=\"0 0 24 24\" fill=\"none\" stroke=\"currentColor\" stroke-width=\"1.6\" stroke-linecap=\"round\" stroke-linejoin=\"round\" aria-hidden=\"true\">' + (window.ICONS[name] || '') + '</svg>'; };\n");
console.log('vendor done; icons', Object.keys(out).length);
